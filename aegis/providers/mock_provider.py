import asyncio
import time
from aegis.providers.base import BaseLLMProvider
from aegis.core.models import (
    ChatCompletionRequest,
    ChatCompletionResponse,
    ChatChoice,
    ChatChoiceMessage,
    UsageStats,
)

class MockProvider(BaseLLMProvider):
    """
    High-speed mock LLM provider for zero-cost testing, high-concurrency benchmarks,
    and deliberate fault-injection (rate limits, timeouts, server errors).
    """

    def __init__(
        self,
        name: str = "mock",
        simulated_delay_ms: float = 300.0,
        fail_rate_limit: bool = False,
        fail_server_error: bool = False,
    ):
        self._name = name
        self.simulated_delay_ms = simulated_delay_ms
        self.fail_rate_limit = fail_rate_limit
        self.fail_server_error = fail_server_error

    @property
    def name(self) -> str:
        return self._name

    async def generate(self, request: ChatCompletionRequest) -> ChatCompletionResponse:
        start_time = time.time()

        # Simulate upstream network latency
        if self.simulated_delay_ms > 0:
            await asyncio.sleep(self.simulated_delay_ms / 1000.0)

        # Fault injection
        if self.fail_rate_limit:
            raise RuntimeError("HTTP 429: Too Many Requests (Rate limit exceeded)")

        if self.fail_server_error:
            raise RuntimeError("HTTP 503: Service Unavailable (Upstream model overloaded)")

        prompt_text = request.get_prompt_text()
        prompt_tokens = len(prompt_text.split())
        reply_content = f"Synthesized answer to query: '{request.messages[-1].content}'. Generated by {self._name}."
        completion_tokens = len(reply_content.split())

        latency_ms = (time.time() - start_time) * 1000.0

        return ChatCompletionResponse(
            model=f"{self._name}-v1",
            choices=[
                ChatChoice(
                    message=ChatChoiceMessage(role="assistant", content=reply_content),
                    finish_reason="stop",
                )
            ],
            usage=UsageStats(
                prompt_tokens=prompt_tokens,
                completion_tokens=completion_tokens,
                total_tokens=prompt_tokens + completion_tokens,
            ),
            cached=False,
            provider_used=self._name,
            latency_ms=round(latency_ms, 2),
        )
